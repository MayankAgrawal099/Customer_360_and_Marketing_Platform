-- Tableau extract: one row per CRM customer (buyers and non-buyers), segment, RFM, CLV and profile in one flat table.
-- No name or email: the dashboard does not need them. Flags are exported as 1/0 by src/export_for_tableau.py.
select
    s.customer_id,
    s.segment,
    s.segment_order,
    s.is_buyer,
    s.r_score,
    s.f_score,
    s.m_score,
    s.rfm_code,
    s.rfm_total,
    s.recency_days,
    s.orders,
    s.historical_net_revenue_usd,
    s.predicted_revenue_90d_usd,
    s.predicted_revenue_12m_usd,
    s.clv_12m_usd,
    s.country,
    s.marketing_opt_in,
    s.has_linked_device,
    s.first_order_channel_group,
    s.first_session_channel_group,
    c.created_date,
    c.created_month,
    c.is_repeat_buyer,
    c.gross_revenue_usd,
    c.refunded_orders,
    c.avg_order_value_usd,
    c.first_order_date,
    c.last_order_date,
    c.web_orders,
    c.app_orders,
    c.linked_devices,
    c.sessions,
    c.converted_sessions,
    c.has_high_confidence_link,
    (select date_add(max(order_date), interval 1 day) from `da02-customer360.marts.fct_orders`) as as_of_date
from `da02-customer360.marts.fct_customer_segments` as s
inner join `da02-customer360.marts.dim_customers` as c on c.customer_id = s.customer_id
